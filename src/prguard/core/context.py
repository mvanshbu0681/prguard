#: E9, vendored by path segment.
VENDORED_SEGMENTS = frozenset({"vendor", "vendored", "third_party", "thirdparty", "node_modules"})

#: E9, vendored by directory name prefix (a virtualenv can sit anywhere in the tree).
VENDORED_PREFIXES = (".venv", "venv", "site-packages", ".tox", ".eggs")

#: E9, generated by directory.
GENERATED_DIRECTORIES = frozenset({"dist", "build", "__generated__", "generated"})

#: E9, generated by file name.
_GENERATED_NAMES = re.compile(r"(_pb2(_grpc)?\.pyi?|\.min\.(js|css)|\.g\.dart|_generated\.[a-z]+)$")

