#: §4.4's path-sensitivity table. Deliberately matched against the whole POSIX path so that
#: ``app/auth/session.py`` scores on ``auth`` — and deliberately *not* containing bare words
#: like ``session`` or ``token``, which would score ``app/db/session.py`` as an auth path and
#: quietly inflate a quarter of its severity.
SENSITIVE_PATH = re.compile(
    r"(^|/)(auth|authn|authz|login|signin|signup|oauth|sso|saml|iam)(/|_|-|\.|$)"
    r"|(^|/)(billing|payments?|checkout|charges?|refunds?|invoices?|payouts?|subscriptions?"
    r"|stripe|paypal)(/|_|-|\.|$)"
    r"|(^|/)(crypto|cipher|signing|keystore|keys|secrets?|credentials?|password|passwd|jwt"
    r"|hmac)(/|_|-|\.|$)"
    r"|(^|/)(migrations?|alembic)(/|_|-|\.|$)"
    r"|(^|/)(pii|gdpr|personal_data|ssn|passport)(/|_|-|\.|$)"
    r"|(^|/)(permissions?|rbac|acl)(/|_|-|\.|$)",
    re.IGNORECASE,
)

#: §4.4: infra / config / CI paths score 0.6.
INFRASTRUCTURE_PATH = re.compile(
    r"(^|/)(infra|infrastructure|terraform|k8s|kubernetes|helm|charts|deploy|deployment"
    r"|ansible|docker|\.github|\.circleci|\.gitlab-ci\.yml|ci|config|conf|settings|env)"
    r"(/|_|-|\.|$)",
    re.IGNORECASE,
)

SENSITIVITY_SENSITIVE = 1.0
SENSITIVITY_INFRASTRUCTURE = 0.6
SENSITIVITY_NONE = 0.0

#: The reason recorded against a file dropped for budget rather than for class (E5).
BUDGET_REASON = "budget"

#: Degradation keys the pipeline surfaces on the run (E5/E6).
TRUNCATED_DEGRADATION = "context_truncated"
MAX_FILES_DEGRADATION = "context_max_files_exceeded"

_HUNK_SPLIT = re.compile(r"(?m)^(?=@@ )")


@dataclass(frozen=True)
class ChangedFile:
    """One changed file as S1 fetched it — patch, counts and (when fetched) head content."""

    path: str
    change_status: FileChangeStatus = "modified"
    patch: str = ""
    additions: int = 0
    deletions: int = 0
    previous_path: str | None = None
    content: str | bytes | None = None

    @property
    def changed_lines(self) -> int:
        return self.additions + self.deletions

    @classmethod
    def from_github(
        cls, entry: Mapping[str, Any], *, content: str | bytes | None = None
    ) -> ChangedFile:
        """Build from one element of a ``GET …/pulls/{n}/files`` body.

        GitHub omits ``patch`` entirely for binary files, which is itself a signal and is why
        the default is an empty patch rather than an error.
        """
        status = str(entry.get("status", "modified"))
        return cls(
            path=str(entry["filename"]),
            change_status=status if status in _CHANGE_STATUSES else "modified",  # type: ignore[arg-type]
            patch=str(entry.get("patch") or ""),
            additions=int(entry.get("additions", 0)),
            deletions=int(entry.get("deletions", 0)),
            previous_path=entry.get("previous_filename"),
            content=content,
        )


@dataclass(frozen=True)
class ContextSelection:
    """The S2 result: what the specialists see, what was left out, and why.

    ``estimated_tokens`` is the cost of the **patches** that survived, which is what E5's
    budget governs and what E5 truncates. Files fetched whole as referenced context are
    requested separately and are not spent from this budget.
    """

    files: tuple[FileContext, ...] = ()
    excluded: tuple[FileContext, ...] = ()
    excluded_reasons: Mapping[str, str] = field(default_factory=dict)
    omitted_paths: tuple[str, ...] = ()
    truncated_paths: tuple[str, ...] = ()
    truncated: bool = False
    files_changed: int = 0
    estimated_tokens: int = 0
    risk_tier: RiskTier = "standard"
    degradations: tuple[str, ...] = ()

    @property
    def supplied_paths(self) -> tuple[str, ...]:
        return tuple(supplied.path for supplied in self.files)

    @property
    def files_reviewed(self) -> int:
        return len(self.files)

    @property
    def files_excluded(self) -> int:
        return len(self.excluded_reasons)

    def banner(self) -> str | None:
        """E6's review-body line, or ``None`` when nothing was left out."""
        if not self.truncated:
            return None
        return (
            f"Reviewed {self.files_reviewed} of {self.files_changed} changed files "
            "(budget-limited)."
        )


def build_context(
    files: Sequence[ChangedFile],
    *,
    token_budget: int = DEFAULT_TOKEN_BUDGET,
    max_files: int = DEFAULT_MAX_FILES,
) -> ContextSelection:
    """Classify, order, budget and report (spec §4.1 S2, E5/E6/E9).

    The order is the documented one and the tie-break is the path, so the same PR produces the
    same context on every run — which is what makes a review reproducible enough to argue with.
    """
    classified = [(changed, classify(changed.path, content=changed.content)) for changed in files]

    excluded: list[FileContext] = []
    reasons: dict[str, str] = {}
    for changed, classification in classified:
        if is_excluded(classification):
            reasons[changed.path] = classification
            excluded.append(_file_context(changed, classification, patch=""))

    candidates = [
        (changed, classification)
        for changed, classification in classified
        if not is_excluded(classification)
    ]
    candidates.sort(key=lambda item: _ordering_key(item[0]))

    degradations: list[str] = []
    omitted: list[str] = []
    if len(candidates) > max_files:
        degradations.append(MAX_FILES_DEGRADATION)
        omitted.extend(changed.path for changed, _ in candidates[max_files:])
        candidates = candidates[:max_files]

    supplied: list[FileContext] = []
    truncated_paths: list[str] = []
    spent = 0
    for changed, classification in candidates:
        remaining = token_budget - spent
        patch, was_truncated = _fit(changed.patch, remaining)
        if not patch and changed.patch:
            omitted.append(changed.path)
            continue
        if was_truncated:
            truncated_paths.append(changed.path)
        spent += estimate_tokens(patch)
        supplied.append(_file_context(changed, classification, patch=patch))

    for path in omitted:
        reasons[path] = BUDGET_REASON

    truncated = bool(omitted or truncated_paths)
    if truncated and TRUNCATED_DEGRADATION not in degradations:
        degradations.append(TRUNCATED_DEGRADATION)

    return ContextSelection(
        files=tuple(supplied),
        excluded=tuple(excluded),
        excluded_reasons=dict(sorted(reasons.items())),
        omitted_paths=tuple(omitted),
        truncated_paths=tuple(truncated_paths),
        truncated=truncated,
        files_changed=len(files),
        estimated_tokens=spent,
        risk_tier=risk_tier([changed for changed, _ in candidates]),
        degradations=tuple(degradations),
    )


# ---------------------------------------------------------------------------
# Classification (E9)
# ---------------------------------------------------------------------------


def classify(path: str, *, content: str | bytes | None = None) -> FileClassification:
    """E9's classifier. Order matters: a lockfile inside ``vendor/`` is vendored, not a lockfile.

    ``content`` is the head bytes when we have them. Without them the extension allowlist is
    the only signal available, and an unknown extension is treated as binary — failing closed,
    since sending a model an unreadable blob costs tokens and buys nothing.
    """
    if _is_vendored(path):
        return "vendored"
    if _is_lockfile(path):
        return "lockfile"
    if _is_generated(path, content):
        return "generated"
    if _is_binary(path, content):
        return "binary"
    if _TEST_PATHS.search(path):
        return "test"
    return "source"


def is_excluded(classification: FileClassification) -> bool:
    """Whether E9 keeps this class out of specialist context and out of findings entirely."""
    return classification in ("binary", "generated", "vendored", "lockfile")


def language_of(path: str) -> str:
    """The language label a finding carries. ``unknown`` can never block a merge (§4.4)."""
    return LANGUAGES.get(_suffix(path), "unknown")


def path_sensitivity(path: str) -> float:
    """§4.4: auth/payments/crypto/migrations/PII = 1.0 · infra/config/CI = 0.6 · else 0.0."""
    if SENSITIVE_PATH.search(path):
        return SENSITIVITY_SENSITIVE
    if INFRASTRUCTURE_PATH.search(path):
        return SENSITIVITY_INFRASTRUCTURE
    return SENSITIVITY_NONE


def risk_tier(files: Sequence[ChangedFile]) -> RiskTier:
    """§11.2 assumption 11: ≤10 changed lines trivial · ≤200 standard · else full.

    A sensitive path forces ``full`` however small the diff — a one-line change to an auth
    check is exactly the change that deserves four specialists rather than two.
    """
    if any(path_sensitivity(changed.path) >= SENSITIVITY_SENSITIVE for changed in files):
        return "full"
    changed_lines = sum(changed.changed_lines for changed in files)
    if changed_lines <= TRIVIAL_MAX_CHANGED_LINES:
        return "trivial"
    if changed_lines <= STANDARD_MAX_CHANGED_LINES:
        return "standard"
    return "full"


def symbols_in(source: str) -> tuple[str, ...]:
    """Top-level and nested definitions as ``Class.method``, from the head AST.

    Returns ``()`` for anything that does not parse (E28): a degraded symbol list costs some
    severity precision, an exception in S2 costs the run.
    """
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError, RecursionError):
        return ()
    found: list[str] = []

    def walk(node: ast.AST, prefix: str) -> None:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
                qualified = f"{prefix}{child.name}"
                found.append(qualified)
                walk(child, f"{qualified}.")

    walk(tree, "")
    return tuple(found)


def estimate_tokens(text: str) -> int:
    """Characters ÷ 4, rounded up. Stable across runs, which matters more than being exact."""
    if not text:
        return 0
    return (len(text) + CHARACTERS_PER_TOKEN - 1) // CHARACTERS_PER_TOKEN


