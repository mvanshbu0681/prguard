_CHANGE_STATUSES = ("added", "modified", "removed", "renamed")


def _ordering_key(changed: ChangedFile) -> tuple[float, int, str]:
    """E5's order: sensitivity desc, change size asc, then path so ties never wobble."""
    return (-path_sensitivity(changed.path), changed.changed_lines, changed.path)


def _fit(patch: str, budget: int) -> tuple[str, bool]:
    """Cut ``patch`` down to the largest hunks that fit in ``budget`` (E5)."""
    if budget <= 0:
        return ("", bool(patch))
    if estimate_tokens(patch) <= budget:
        return (patch, False)

    hunks = [hunk for hunk in _HUNK_SPLIT.split(patch) if hunk.strip()]
    if len(hunks) <= 1:
        return ("", True)

    ordered = sorted(
        enumerate(hunks), key=lambda item: (-len(item[1].splitlines()), item[0])
    )
    kept: list[int] = []
    spent = 0
    for index, hunk in ordered:
        cost = estimate_tokens(hunk)
        if spent + cost <= budget:
            kept.append(index)
            spent += cost
    if not kept:
        return ("", True)
    return ("".join(hunks[index] for index in sorted(kept)), True)


def _file_context(
    changed: ChangedFile, classification: FileClassification, *, patch: str
) -> FileContext:
    text = changed.content if isinstance(changed.content, str) else None
    return FileContext(
        path=changed.path,
        language=language_of(changed.path),
        change_status=changed.change_status,
        classification=classification,
        line_map=parse_patch(
            patch or None, path=changed.path, change_status=changed.change_status
        ).line_map,
        patch=patch,
        content=text,
        symbols=symbols_in(text) if text and language_of(changed.path) == "python" else (),
        previous_path=changed.previous_path,
        excluded_reason=classification if is_excluded(classification) else None,
    )


def _segments(path: str) -> tuple[str, ...]:
    return tuple(part for part in path.split("/") if part)


def _suffix(path: str) -> str:
    name = _segments(path)[-1] if _segments(path) else path
    dot = name.rfind(".")
    return name[dot:].lower() if dot > 0 else ""


def _is_vendored(path: str) -> bool:
    segments = _segments(path)
    directories = segments[:-1] if len(segments) > 1 else ()
    return any(
        directory in VENDORED_SEGMENTS or directory.startswith(VENDORED_PREFIXES)
        for directory in directories
    )


def _is_lockfile(path: str) -> bool:
    segments = _segments(path)
    return bool(segments) and segments[-1] in LOCKFILE_NAMES


def _is_generated(path: str, content: str | bytes | None) -> bool:
    segments = _segments(path)
    if any(directory in GENERATED_DIRECTORIES for directory in segments[:-1]):
        return True
    if segments and _GENERATED_NAMES.search(segments[-1]):
        return True
    return _has_generated_header(content)


def _has_generated_header(content: str | bytes | None) -> bool:
    text = _as_text(content)
    if text is None:
        return False
    head = "\n".join(text.splitlines()[:GENERATED_HEADER_LINES]).lower()
    return any(marker in head for marker in GENERATED_HEADER_MARKERS)


def _is_binary(path: str, content: str | bytes | None) -> bool:
    if isinstance(content, bytes) and b"\x00" in content:
        return True
    if isinstance(content, str) and "\x00" in content:
        return True
    segments = _segments(path)
    name = segments[-1] if segments else path
    if name in TEXTUAL_FILENAMES:
        return False
    return _suffix(path) not in LANGUAGES


def _as_text(content: str | bytes | None) -> str | None:
    if content is None:
        return None
    if isinstance(content, str):
        return content
    try:
        return content.decode("utf-8")
    except UnicodeDecodeError:
        return None


