"""S2 — what the model is allowed to see (spec §4.1, §7 E5/E6/E9, AC-26). Pure, no I/O (§4.3).

The file bytes arrive already fetched; this module decides what survives, in what order, and
how much of it. Three decisions, each with a reason the API can state out loud:

* **Classification (E9).** Binary, generated, vendored and lockfile paths are dropped before a
  specialist sees them — a review that raises a finding inside ``vendor/`` or a 7 930-line
  ``package-lock.json`` diff is noise, and it costs real tokens to produce. Every exclusion
  carries its reason into ``/result`` so "we reviewed 41 of 47 files" is never a mystery.
* **Compression (E5/E6).** When the diff will not fit in ``CONTEXT_TOKEN_BUDGET``, files are
  ordered by path sensitivity descending, then by change size ascending — small changes to
  auth and payments first, because that is where a missed bug costs the most — and each
  over-budget patch is cut down to its largest hunks. Ties break on path so the selection is
  reproducible; it does not depend on the order GitHub happened to return the files in.
* **Saying so.** ``truncated``, ``omitted_paths`` and ``excluded_reasons`` are part of the
  result. Never silently review 3 of 40 files.

Risk tiering (§11.2 assumption 11) lives here too, because it is a function of the same two
things: how much changed, and how sensitive the paths are.
"""

