#: §4.8 defaults, repeated here so a caller can build a context without a Settings object.
DEFAULT_TOKEN_BUDGET = 120_000
DEFAULT_MAX_FILES = 300

#: §11.2 assumption 11 — changed-line thresholds for the specialist set.
TRIVIAL_MAX_CHANGED_LINES = 10
STANDARD_MAX_CHANGED_LINES = 200

#: A crude but stable token estimate: four characters per token. Exact enough for a budget
#: decision and, more importantly, identical on every run — a tokeniser that changed with a
#: library upgrade would make AC-26's determinism claim a lie.
CHARACTERS_PER_TOKEN = 4

#: E9, lockfiles by exact name.
